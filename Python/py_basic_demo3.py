"""
编写一个 BMI 计算器程序，要求如下：

1. **用户输入**：通过 `input()` 函数获取用户的身高（单位：米）和体重（单位：千克）。
2. **计算 BMI**：使用公式 `BMI = 体重(kg) / 身高(m)²` 计算 BMI 值。
3. **判断分类**：根据 BMI 值判断身体状况（参考中国成人标准）：
   - BMI < 18.5：偏瘦
   - 18.5 ≤ BMI < 24：正常
   - 24 ≤ BMI < 28：超重
   - BMI ≥ 28：肥胖
4. **输出结果**：使用 f-string 格式化输出用户的 BMI 值和分类结果。
5. **健康建议**：根据分类结果给出相应的健康建议，例如：
   - 偏瘦：建议适当增加营养摄入，进行适量运动
   - 正常：保持良好的生活习惯
   - 超重/肥胖：建议控制饮食，增加运动量

**示例输出**：
请输入您的身高（米）：1.75
请输入您的体重（千克）：70
您的 BMI 值为：22.86
身体状况：正常
建议：保持良好的生活习惯，继续保持！
"""

height = float(input("请输入您的身高（米）"))
weight = float(input("请输入您的体重（千克）"))

BIM = weight / (height**2)

print(f"您的 BMI 值为：{BIM}")

if BIM < 18.5:
    print(f"身体状况：偏瘦")
    print(f"建议：适当增加营养摄入，进行适量运动")
elif 24 <= BIM < 28:
    print(f"身体状况：正常")
    print(f"建议：保持良好的生活习惯")
else:
    print(f"身体状况：超重")
    print(f"建议：控制饮食，增加运动量")
